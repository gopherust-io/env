package codegen

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"
	"strconv"
	"strings"

	"golang.org/x/mod/module"

	"github.com/gopherust-io/env"
	"github.com/gopherust-io/env/internal/tag"
)

type Options struct {
	Package  string
	TypeName string
	Module   string
	Fields   []tag.Field
}

func Generate(opts Options) ([]byte, error) {
	if env.IsEmpty(opts.Module) {
		opts.Module = "github.com/gopherust-io/env"
	}
	if err := module.CheckImportPath(opts.Module); err != nil {
		return nil, fmt.Errorf("invalid module import path %q: %w", opts.Module, err)
	}
	if !token.IsIdentifier(opts.Package) {
		return nil, fmt.Errorf("invalid package name %q", opts.Package)
	}
	if !token.IsIdentifier(opts.TypeName) {
		return nil, fmt.Errorf("invalid type name %q", opts.TypeName)
	}
	if err := validateFields(opts.Fields); err != nil {
		return nil, err
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by envgen. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", opts.Package)
	b.WriteString("import (\n")
	fmt.Fprintf(&b, "\tenv %s\n", strconv.Quote(opts.Module))
	if needsTimeImport(opts.Fields) {
		b.WriteString("\t\"time\"\n")
	}
	b.WriteString(")\n\n")

	fmt.Fprintf(&b, "func Load%s() (%s, error) {\n", opts.TypeName, opts.TypeName)
	b.WriteString("\tvar cfg " + opts.TypeName + "\n")
	fmt.Fprintf(&b, "\tif err := load%s(&cfg, env.Snapshot()); err != nil {\n", opts.TypeName)
	b.WriteString("\t\treturn cfg, err\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn cfg, nil\n")
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "func Reload%s(cfg *%s) error {\n", opts.TypeName, opts.TypeName)
	b.WriteString("\tenv.Reload()\n")
	// Load into a fresh value so unset keys clear previous (including sensitive) fields.
	fmt.Fprintf(&b, "\tvar next %s\n", opts.TypeName)
	fmt.Fprintf(&b, "\tif err := load%s(&next, env.Snapshot()); err != nil {\n", opts.TypeName)
	b.WriteString("\t\treturn err\n")
	b.WriteString("\t}\n")
	b.WriteString("\t*cfg = next\n")
	b.WriteString("\treturn nil\n")
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "func MustReload%s(cfg *%s) {\n", opts.TypeName, opts.TypeName)
	fmt.Fprintf(&b, "\tif err := Reload%s(cfg); err != nil {\n", opts.TypeName)
	b.WriteString("\t\tpanic(err)\n")
	b.WriteString("\t}\n")
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "func Load%sFrom(snap *env.EnvSnapshot) (%s, error) {\n", opts.TypeName, opts.TypeName)
	fmt.Fprintf(&b, "\tvar cfg %s\n", opts.TypeName)
	fmt.Fprintf(&b, "\tif err := load%s(&cfg, snap); err != nil {\n", opts.TypeName)
	b.WriteString("\t\treturn cfg, err\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn cfg, nil\n")
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "func MustLoad%s() %s {\n", opts.TypeName, opts.TypeName)
	fmt.Fprintf(&b, "\tcfg, err := Load%s()\n", opts.TypeName)
	b.WriteString("\tif err != nil {\n")
	b.WriteString("\t\tpanic(err)\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn cfg\n")
	b.WriteString("}\n\n")

	if hasSensitive(opts.Fields) {
		emitMasked(&b, opts)
	}

	emitAudit(&b, opts)

	fmt.Fprintf(&b, "func load%s(cfg *%s, snap *env.EnvSnapshot) error {\n", opts.TypeName, opts.TypeName)
	b.WriteString("\tvar errs []env.FieldError\n")
	for _, f := range opts.Fields {
		emitFieldLoad(&b, f, "cfg")
	}
	b.WriteString("\treturn env.NewError(errs)\n")
	b.WriteString("}\n")

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return b.Bytes(), err
	}
	return formatted, nil
}

func emitMasked(b *bytes.Buffer, opts Options) {
	fmt.Fprintf(b, "func (c %s) Masked() %s {\n", opts.TypeName, opts.TypeName)
	b.WriteString("\tout := c\n")
	emitMaskedFields(b, opts.Fields, "out")
	b.WriteString("\treturn out\n")
	b.WriteString("}\n\n")
}

func emitAudit(b *bytes.Buffer, opts Options) {
	schema := tag.SchemaFields(opts.Fields)
	varName := toCamelLower(opts.TypeName) + "AuditSchema"
	fmt.Fprintf(b, "var %s = []env.SchemaField{\n", varName)
	for _, f := range schema {
		fmt.Fprintf(b, "\t{Key: %q, FieldPath: %q", f.Key, f.FieldPath)
		if !env.IsEmpty(f.Default) {
			fmt.Fprintf(b, ", Default: %q", f.Default)
		}
		if !env.IsEmpty(f.Prefix) {
			fmt.Fprintf(b, ", Prefix: %q", f.Prefix)
		}
		if f.Required {
			b.WriteString(", Required: true")
		}
		if f.HasDefault {
			b.WriteString(", HasDefault: true")
		}
		if f.Sensitive {
			b.WriteString(", Sensitive: true")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(b, "func Audit%s(snap *env.EnvSnapshot) env.AuditReport {\n", opts.TypeName)
	fmt.Fprintf(b, "\treturn env.Audit(snap, %s, env.AuditOptions{})\n", varName)
	b.WriteString("}\n\n")

	fmt.Fprintf(b, "func Audit%sWithOptions(snap *env.EnvSnapshot, opts env.AuditOptions) env.AuditReport {\n", opts.TypeName)
	fmt.Fprintf(b, "\treturn env.Audit(snap, %s, opts)\n", varName)
	b.WriteString("}\n\n")

	fmt.Fprintf(b, "func Audit%sFromEnviron() env.AuditReport {\n", opts.TypeName)
	fmt.Fprintf(b, "\treturn Audit%s(env.Snapshot())\n", opts.TypeName)
	b.WriteString("}\n\n")
}

func toCamelLower(name string) string {
	if name == "" {
		return name
	}
	return strings.ToLower(name[:1]) + name[1:]
}

func emitMaskedFields(b *bytes.Buffer, fields []tag.Field, target string) {
	for _, f := range fields {
		if f.IsNested {
			childTarget := target + "." + f.Name
			if isPointerField(f) {
				fmt.Fprintf(b, "\tif %s != nil {\n", childTarget)
				b.WriteString("\t\t{\n")
				fmt.Fprintf(b, "\t\t\ttmp := *%s\n", childTarget)
				fmt.Fprintf(b, "\t\t\t%s = &tmp\n", childTarget)
				emitMaskedFields(b, f.Children, childTarget)
				b.WriteString("\t\t}\n")
				b.WriteString("\t}\n")
			} else {
				emitMaskedFields(b, f.Children, childTarget)
			}
			continue
		}
		if !f.Sensitive {
			continue
		}
		elem := strings.TrimPrefix(f.GoType, "*")
		if elem != "string" {
			continue
		}
		if f.IsPointer || strings.HasPrefix(f.GoType, "*") {
			b.WriteString("\t{\n")
			b.WriteString("\t\tv := env.SensitiveMask\n")
			fmt.Fprintf(b, "\t\t%s.%s = &v\n", target, f.Name)
			b.WriteString("\t}\n")
			continue
		}
		fmt.Fprintf(b, "\t%s.%s = env.SensitiveMask\n", target, f.Name)
	}
}

func emitFieldLoad(b *bytes.Buffer, f tag.Field, target string) {
	if f.IsNested {
		childTarget := target + "." + f.Name
		if isPointerField(f) {
			elem := strings.TrimPrefix(f.GoType, "*")
			fmt.Fprintf(b, "\tif %s == nil {\n", childTarget)
			fmt.Fprintf(b, "\t\t%s = &%s{}\n", childTarget, elem)
			b.WriteString("\t}\n")
		}
		for _, child := range f.Children {
			emitFieldLoad(b, child, childTarget)
		}
		return
	}
	emitLeafLoad(b, f, target)
}

func emitLeafLoad(b *bytes.Buffer, f tag.Field, target string) {
	key := f.Prefix + f.EnvKey
	fieldLabel := f.FieldPath
	if env.IsEmpty(fieldLabel) {
		fieldLabel = f.Name
	}

	fmt.Fprintf(b, "\t{\n")
	fmt.Fprintf(b, "\t\tkey := %q\n", key)
	b.WriteString("\t\traw, ok := snap.Lookup(key)\n")
	b.WriteString("\t\tif !ok || env.IsEmpty(raw) {\n")
	if f.Required && env.IsEmpty(f.Default) {
		fmt.Fprintf(b, "\t\t\tenv.AppendRequired(&errs, %q, key)\n", fieldLabel)
	} else if !env.IsEmpty(f.Default) {
		emitDefaultAssign(b, f, target)
	} else if f.IsPointer {
		fmt.Fprintf(b, "\t\t\t%s.%s = nil\n", target, f.Name)
	}
	b.WriteString("\t\t} else {\n")

	if f.Expand {
		b.WriteString("\t\t\traw = env.Expand(raw, snap)\n")
	}

	if f.Unmarshal {
		if f.IsPointer || strings.HasPrefix(f.GoType, "*") {
			elem := strings.TrimPrefix(f.GoType, "*")
			fmt.Fprintf(b, "\t\t\tif %s.%s == nil {\n", target, f.Name)
			fmt.Fprintf(b, "\t\t\t\t%s.%s = new(%s)\n", target, f.Name, elem)
			b.WriteString("\t\t\t}\n")
		}
		fmt.Fprintf(b, "\t\t\tif err := %s.%s.UnmarshalEnv(key, raw); err != nil {\n", target, f.Name)
		emitAppendParse(b, f, fieldLabel, "raw")
		b.WriteString("\t\t\t}\n")
	} else {
		emitParseAssign(b, f, target, fieldLabel)
	}
	b.WriteString("\t\t}\n")
	b.WriteString("\t}\n")
}

func emitAppendParse(b *bytes.Buffer, f tag.Field, fieldLabel, valueExpr string) {
	fn := "AppendParse"
	if f.Sensitive {
		fn = "AppendParseSensitive"
	}
	fmt.Fprintf(b, "\t\t\t\tenv.%s(&errs, %q, key, %s, err)\n", fn, fieldLabel, valueExpr)
}

func emitAppendParseQuoted(b *bytes.Buffer, f tag.Field, fieldLabel, value string) {
	fn := "AppendParse"
	if f.Sensitive {
		fn = "AppendParseSensitive"
	}
	fmt.Fprintf(b, "\t\t\t\tenv.%s(&errs, %q, key, %q, err)\n", fn, fieldLabel, value)
}

func emitAssign(b *bytes.Buffer, f tag.Field, target string) {
	if f.IsPointer {
		fmt.Fprintf(b, "\t\t\t\t%s.%s = &v\n", target, f.Name)
		return
	}
	fmt.Fprintf(b, "\t\t\t\t%s.%s = v\n", target, f.Name)
}

func emitDefaultAssign(b *bytes.Buffer, f tag.Field, target string) {
	val := f.Default
	elem := strings.TrimPrefix(f.GoType, "*")
	rawExpr := emitDefaultRawExpr(b, f, val)
	switch {
	case elem == "string":
		fmt.Fprintf(b, "\t\t\tv := %s\n", rawExpr)
		if f.IsPointer {
			fmt.Fprintf(b, "\t\t\t%s.%s = &v\n", target, f.Name)
		} else {
			fmt.Fprintf(b, "\t\t\t%s.%s = v\n", target, f.Name)
		}
	case elem == "bool":
		fmt.Fprintf(b, "\t\t\tv, err := env.ParseBool(%s)\n", rawExpr)
		b.WriteString("\t\t\tif err != nil {\n")
		emitAppendParseQuoted(b, f, fieldLabelOrName(f), val)
		b.WriteString("\t\t\t} else {\n")
		emitAssign(b, f, target)
		b.WriteString("\t\t\t}\n")
	case elem == "time.Duration":
		fmt.Fprintf(b, "\t\t\tv, err := env.ParseDuration(%s)\n", rawExpr)
		b.WriteString("\t\t\tif err != nil {\n")
		emitAppendParseQuoted(b, f, fieldLabelOrName(f), val)
		b.WriteString("\t\t\t} else {\n")
		emitAssign(b, f, target)
		b.WriteString("\t\t\t}\n")
	case elem == "time.Time":
		layout := f.Layout
		if env.IsEmpty(layout) {
			layout = "2006-01-02T15:04:05Z07:00"
		}
		fmt.Fprintf(b, "\t\t\tv, err := env.ParseTime(%s, %q)\n", rawExpr, layout)
		b.WriteString("\t\t\tif err != nil {\n")
		emitAppendParseQuoted(b, f, fieldLabelOrName(f), val)
		b.WriteString("\t\t\t} else {\n")
		emitAssign(b, f, target)
		b.WriteString("\t\t\t}\n")
	case strings.HasPrefix(elem, "int"), strings.HasPrefix(elem, "uint"), strings.HasPrefix(elem, "float"):
		parser, _ := parseFunc(elem)
		fmt.Fprintf(b, "\t\t\tv, err := env.%s(%s)\n", parser, rawExpr)
		b.WriteString("\t\t\tif err != nil {\n")
		emitAppendParseQuoted(b, f, fieldLabelOrName(f), val)
		b.WriteString("\t\t\t} else {\n")
		emitAssign(b, f, target)
		b.WriteString("\t\t\t}\n")
	case f.IsSlice && f.SliceElem == "string":
		sep := f.Sep
		if env.IsEmpty(sep) {
			sep = ","
		}
		fmt.Fprintf(b, "\t\t\tv, err := env.ParseStringSlice(%s, %q)\n", rawExpr, sep)
		b.WriteString("\t\t\tif err != nil {\n")
		emitAppendParseQuoted(b, f, fieldLabelOrName(f), val)
		b.WriteString("\t\t\t} else {\n")
		fmt.Fprintf(b, "\t\t\t\t%s.%s = v\n", target, f.Name)
		b.WriteString("\t\t\t}\n")
	case f.IsSlice && f.SliceElem == "int":
		sep := f.Sep
		if env.IsEmpty(sep) {
			sep = ","
		}
		fmt.Fprintf(b, "\t\t\tv, err := env.ParseIntSlice(%s, %q)\n", rawExpr, sep)
		b.WriteString("\t\t\tif err != nil {\n")
		emitAppendParseQuoted(b, f, fieldLabelOrName(f), val)
		b.WriteString("\t\t\t} else {\n")
		fmt.Fprintf(b, "\t\t\t\t%s.%s = v\n", target, f.Name)
		b.WriteString("\t\t\t}\n")
	case f.IsMap && f.MapKey == "string" && f.MapValue == "string":
		sep := f.Sep
		if env.IsEmpty(sep) {
			sep = ","
		}
		kvSep := f.KvSep
		if env.IsEmpty(kvSep) {
			kvSep = ":"
		}
		fmt.Fprintf(b, "\t\t\tv, err := env.ParseStringMap(%s, %q, %q)\n", rawExpr, sep, kvSep)
		b.WriteString("\t\t\tif err != nil {\n")
		emitAppendParseQuoted(b, f, fieldLabelOrName(f), val)
		b.WriteString("\t\t\t} else {\n")
		fmt.Fprintf(b, "\t\t\t\t%s.%s = v\n", target, f.Name)
		b.WriteString("\t\t\t}\n")
	default:
		fmt.Fprintf(b, "\t\t\t_ = %s // unsupported default for %s\n", rawExpr, f.GoType)
	}
}

// emitDefaultRawExpr returns a Go expression for the default string, expanding when needed.
func emitDefaultRawExpr(b *bytes.Buffer, f tag.Field, val string) string {
	if f.Expand {
		fmt.Fprintf(b, "\t\t\tdefaultRaw := env.Expand(%q, snap)\n", val)
		return "defaultRaw"
	}
	return strconv.Quote(val)
}

func fieldLabelOrName(f tag.Field) string {
	if !env.IsEmpty(f.FieldPath) {
		return f.FieldPath
	}
	return f.Name
}

func emitParseAssign(b *bytes.Buffer, f tag.Field, target, fieldLabel string) {
	elem := strings.TrimPrefix(f.GoType, "*")
	switch {
	case elem == "string":
		if f.IsPointer {
			b.WriteString("\t\t\tv := raw\n")
			fmt.Fprintf(b, "\t\t\t%s.%s = &v\n", target, f.Name)
		} else {
			fmt.Fprintf(b, "\t\t\t%s.%s = raw\n", target, f.Name)
		}
	case elem == "bool":
		b.WriteString("\t\t\tv, err := env.ParseBool(raw)\n")
		b.WriteString("\t\t\tif err != nil {\n")
		emitAppendParse(b, f, fieldLabel, "raw")
		b.WriteString("\t\t\t} else {\n")
		emitAssign(b, f, target)
		b.WriteString("\t\t\t}\n")
	case elem == "time.Duration":
		b.WriteString("\t\t\tv, err := env.ParseDuration(raw)\n")
		b.WriteString("\t\t\tif err != nil {\n")
		emitAppendParse(b, f, fieldLabel, "raw")
		b.WriteString("\t\t\t} else {\n")
		emitAssign(b, f, target)
		b.WriteString("\t\t\t}\n")
	case elem == "time.Time":
		layout := f.Layout
		if env.IsEmpty(layout) {
			layout = "2006-01-02T15:04:05Z07:00"
		}
		fmt.Fprintf(b, "\t\t\tv, err := env.ParseTime(raw, %q)\n", layout)
		b.WriteString("\t\t\tif err != nil {\n")
		emitAppendParse(b, f, fieldLabel, "raw")
		b.WriteString("\t\t\t} else {\n")
		emitAssign(b, f, target)
		b.WriteString("\t\t\t}\n")
	case f.IsSlice && f.SliceElem == "string":
		sep := f.Sep
		if env.IsEmpty(sep) {
			sep = ","
		}
		fmt.Fprintf(b, "\t\t\tv, err := env.ParseStringSlice(raw, %q)\n", sep)
		b.WriteString("\t\t\tif err != nil {\n")
		emitAppendParse(b, f, fieldLabel, "raw")
		b.WriteString("\t\t\t} else {\n")
		fmt.Fprintf(b, "\t\t\t\t%s.%s = v\n", target, f.Name)
		b.WriteString("\t\t\t}\n")
	case f.IsSlice && f.SliceElem == "int":
		sep := f.Sep
		if env.IsEmpty(sep) {
			sep = ","
		}
		fmt.Fprintf(b, "\t\t\tv, err := env.ParseIntSlice(raw, %q)\n", sep)
		b.WriteString("\t\t\tif err != nil {\n")
		emitAppendParse(b, f, fieldLabel, "raw")
		b.WriteString("\t\t\t} else {\n")
		fmt.Fprintf(b, "\t\t\t\t%s.%s = v\n", target, f.Name)
		b.WriteString("\t\t\t}\n")
	case f.IsMap && f.MapKey == "string" && f.MapValue == "string":
		sep := f.Sep
		if env.IsEmpty(sep) {
			sep = ","
		}
		kvSep := f.KvSep
		if env.IsEmpty(kvSep) {
			kvSep = ":"
		}
		fmt.Fprintf(b, "\t\t\tv, err := env.ParseStringMap(raw, %q, %q)\n", sep, kvSep)
		b.WriteString("\t\t\tif err != nil {\n")
		emitAppendParse(b, f, fieldLabel, "raw")
		b.WriteString("\t\t\t} else {\n")
		fmt.Fprintf(b, "\t\t\t\t%s.%s = v\n", target, f.Name)
		b.WriteString("\t\t\t}\n")
	default:
		parser, ok := parseFunc(elem)
		if !ok {
			fmt.Fprintf(b, "\t\t\t_ = raw // unsupported type %s\n", f.GoType)
			return
		}
		fmt.Fprintf(b, "\t\t\tv, err := env.%s(raw)\n", parser)
		b.WriteString("\t\t\tif err != nil {\n")
		emitAppendParse(b, f, fieldLabel, "raw")
		b.WriteString("\t\t\t} else {\n")
		emitAssign(b, f, target)
		b.WriteString("\t\t\t}\n")
	}
}

func parseFunc(goType string) (string, bool) {
	switch goType {
	case "int":
		return "ParseInt", true
	case "int8":
		return "ParseInt8", true
	case "int16":
		return "ParseInt16", true
	case "int32":
		return "ParseInt32", true
	case "int64":
		return "ParseInt64", true
	case "uint":
		return "ParseUint", true
	case "uint8":
		return "ParseUint8", true
	case "uint16":
		return "ParseUint16", true
	case "uint32":
		return "ParseUint32", true
	case "uint64":
		return "ParseUint64", true
	case "float32":
		return "ParseFloat32", true
	case "float64":
		return "ParseFloat64", true
	default:
		return "", false
	}
}

func isPointerField(f tag.Field) bool {
	return f.IsPointer || strings.HasPrefix(f.GoType, "*")
}

func validateFields(fields []tag.Field) error {
	for _, f := range fields {
		if f.IsNested {
			if err := validateFields(f.Children); err != nil {
				return err
			}
			continue
		}
		path := f.FieldPath
		if env.IsEmpty(path) {
			path = f.Name
		}
		if f.Sensitive {
			elem := strings.TrimPrefix(f.GoType, "*")
			if elem != "string" {
				return fmt.Errorf("sensitive field %s must be string or *string, got %s", path, f.GoType)
			}
			if !env.IsEmpty(f.Default) {
				return fmt.Errorf("sensitive field %s cannot have a default value", path)
			}
		}
		if f.Unmarshal {
			if !env.IsEmpty(f.Default) {
				return fmt.Errorf("field %s: UnmarshalEnv types cannot use default (unsupported)", path)
			}
			continue
		}
		if f.IsSlice {
			if f.SliceElem != "string" && f.SliceElem != "int" {
				return fmt.Errorf("unsupported slice element type %s for %s", f.SliceElem, path)
			}
			continue
		}
		if f.IsMap {
			if f.MapKey != "string" || f.MapValue != "string" {
				return fmt.Errorf("unsupported map type for %s (want map[string]string)", path)
			}
			continue
		}
		elem := strings.TrimPrefix(f.GoType, "*")
		switch elem {
		case "string", "bool", "time.Duration", "time.Time":
			continue
		}
		if _, ok := parseFunc(elem); ok {
			continue
		}
		return fmt.Errorf("unsupported field type %s for %s", f.GoType, path)
	}
	return nil
}

func needsTimeImport(_ []tag.Field) bool {
	// Generated loaders call env.ParseTime/ParseDuration and do not reference package time.
	return false
}

func hasSensitive(fields []tag.Field) bool {
	for _, f := range fields {
		if f.Sensitive {
			return true
		}
		if f.IsNested && hasSensitive(f.Children) {
			return true
		}
	}
	return false
}
